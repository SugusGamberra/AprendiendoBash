#!/bin/bash
# Operadores aritmeticos

a=3
b=7

suma=$((a + b))
echo "La suma de $a + $b es $suma"

resta=$((b - a))
echo "La resta de $b - $a es $resta"

multiplicacion=$((a * b))
echo "La multiplicación de $a * $b es $multiplicacion"

division=$((b / a))
echo "La división de $b / $a es $division"


